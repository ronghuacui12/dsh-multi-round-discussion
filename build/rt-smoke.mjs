import {fileURLToPath as repoFileURLToPath} from 'node:url';
const REPO_ROOT=repoFileURLToPath(new URL('../',import.meta.url)).replaceAll('\\','/').replace(/\/$/,'');
import { JSDOM } from 'jsdom';
import fs from 'node:fs';
const html = fs.readFileSync((REPO_ROOT + '/圆桌视图-原型.html'), 'utf8');
const dom = new JSDOM(html, { runScripts: 'dangerously', pretendToBeVisual: true, url: 'http://localhost/' });
const win = dom.window; const doc = win.document;
const out = []; const check = (n, ok, extra) => out.push((ok ? 'PASS ' : 'FAIL ') + n + (extra ? '  [' + extra + ']' : ''));
check('12 个座位热区', doc.querySelectorAll('.seat').length === 12, doc.querySelectorAll('.seat').length);
check('初始 7 个角色', doc.querySelectorAll('.actor').length === 7, doc.querySelectorAll('.actor').length);
check('Q 版 SVG 已渲染', doc.querySelectorAll('.actor svg').length === 7);
check('空座位显示 ＋', doc.querySelectorAll('.seat .vac').length === 5);
check('阶段进度条 8 步', doc.querySelectorAll('.rail .st').length === 8);
check('角色身上有角色标签', doc.querySelectorAll('.actor .cap').length === 7);
const rt = win.__rt;
rt.swap('S2','S1');
check('拖拽换角色：S1/S2 互换', rt.state.seated.S1 === 'proposer-a' && rt.state.seated.S2 === 'lead');
check('交换后角色数量守恒', rt.modelCounts().decisionMaker === 1 && rt.modelCounts().proposer === 3);
rt.picker('S5'); rt.assign('proposer-d');
check('点空座位加模型', rt.state.seated.S5 === 'proposer-d');
const before = doc.querySelectorAll('.actor').length;
check('加完后角色变 8 个', before === 8, before);
rt.edit('S1');
check('右键菜单→编辑抽屉打开', doc.getElementById('drawer').classList.contains('open') && !!doc.getElementById('f_label'));
check('抽屉读到模型信息', doc.getElementById('f_label').value.length > 0 && doc.getElementById('f_model').options.length > 0);
doc.getElementById('f_label').value = '改过的名字'; doc.getElementById('drawerSave').click();
check('保存后抽屉关闭', !doc.getElementById('drawer').classList.contains('open'));
check('保存后角色标签跟着变', doc.body.textContent.indexOf('改过的名字') >= 0);
rt.play();
await new Promise(r => setTimeout(r, 800));
check('演示进入提案阶段', rt.state.phase === 'proposing', rt.state.phase);
check('思考气泡出现(>=3)', doc.querySelectorAll('.bubble.think').length >= 3, doc.querySelectorAll('.bubble.think').length);
check('对话流出现提问与分隔条', doc.querySelectorAll('.msg').length >= 1 && doc.querySelectorAll('.divider').length >= 1);
check('底部审批条此时不显示', doc.getElementById('dock').innerHTML === '');
rt.state.phase = 'approval'; rt.renderAll();
check('切到等待批准→底部审批条出现', doc.getElementById('dock').innerHTML.indexOf('批准并执行') >= 0);
check('主导模型头顶出现 ❗', doc.body.textContent.indexOf('❗') >= 0);
rt.reset();
const fails = out.filter(l => l.indexOf('FAIL') === 0).length;
console.log(out.join('\n'));
console.log('\n总检查 ' + out.length + ' 项，失败 ' + fails + ' 项');
process.exit(fails ? 1 : 0);