import { ToolSandbox, ALL_TOOLS } from 'file:///D:/1/mmd-ui/plugin/lib/core/sandbox.js';
const all = [{ name: 'read' }, { name: 'write' }, { name: 'pwsh' }, { name: 'mcp__desktop__start_process' }, { name: 'brand_new_tool' }];
const out = [];
const ok = (n, c, x) => out.push((c ? 'PASS ' : 'FAIL ') + n + (x ? '  [' + x + ']' : ''));
const wild = new ToolSandbox({ allowedTools: [ALL_TOOLS], requireConfirmationForWrites: false, maxSteps: 0 });
ok('通配符可见全部工具', wild.visibleTools(all).length === all.length, wild.visibleTools(all).length + '/' + all.length);
ok('通配符含未来新增工具', wild.allows('brand_new_tool'));
ok('通配符下 write 直接放行', wild.decide('write').kind === 'allow');
ok('maxSteps=0 -> 不限', wild.maxSteps === Number.POSITIVE_INFINITY, String(wild.maxSteps));
ok('permitted 报告 *', JSON.stringify(wild.permitted) === JSON.stringify(['*']));
const noConfirm = new ToolSandbox({ allowedTools: ['read', 'write'], requireConfirmationForWrites: false, maxSteps: 24 });
ok('白名单内 read 放行', noConfirm.decide('read').kind === 'allow');
ok('逐调用确认关闭后 write 放行', noConfirm.decide('write').kind === 'allow');
ok('白名单外仍拒绝', noConfirm.decide('pwsh').kind === 'deny');
ok('有限步数保持原值', noConfirm.maxSteps === 24, String(noConfirm.maxSteps));
const confirmOn = new ToolSandbox({ allowedTools: ['write'], requireConfirmationForWrites: true, maxSteps: 12 });
ok('开启逐调用确认时 write 仍 confirm', confirmOn.decide('write').kind === 'confirm');
const fails = out.filter((l) => l.startsWith('FAIL')).length;
console.log(out.join('\n'));
console.log('\n' + (out.length - fails) + '/' + out.length + ' passed');
process.exit(fails ? 1 : 0);